create or replace function public.kyro_schedule_followup(p_lead_id integer,p_title text,p_due timestamptz)
returns public.tasks language plpgsql security invoker set search_path='' as $$
declare l public.leads; t public.tasks;
begin
 if auth.uid() is null then raise exception 'Sesión requerida'; end if;
 if length(trim(p_title))=0 or p_due is null then raise exception 'Actividad y fecha requeridas'; end if;
 select * into l from public.leads where id=p_lead_id and user_id=auth.uid() for update;
 if not found then raise exception 'Prospecto no disponible'; end if;
 insert into public.tasks(user_id,title,due,client,priority,completed,attachments,lead_id)
 values(auth.uid(),p_title||' con '||l.name,p_due,l.name,'medium',false,array[]::text[],l.id) returning * into t;
 update public.leads set next_step=jsonb_build_object('type',p_title,'date',p_due),last_activity=now() where id=l.id and user_id=auth.uid();
 return t;
end $$;
revoke all on function public.kyro_schedule_followup(integer,text,timestamptz) from public,anon;
grant execute on function public.kyro_schedule_followup(integer,text,timestamptz) to authenticated;
