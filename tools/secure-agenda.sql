create table kyro_private.ai_usage(user_id uuid not null,day date not null,calls integer not null default 0,primary key(user_id,day));
create or replace function public.kyro_claim_ai_request() returns boolean language plpgsql security definer set search_path='' as $$
declare n integer;
begin
 if auth.uid() is null then return false; end if;
 insert into kyro_private.ai_usage(user_id,day,calls) values(auth.uid(),current_date,1)
 on conflict(user_id,day) do update set calls=kyro_private.ai_usage.calls+1 returning calls into n;
 return n<=60;
end $$;
revoke all on function public.kyro_claim_ai_request() from public,anon;
grant execute on function public.kyro_claim_ai_request() to authenticated;
